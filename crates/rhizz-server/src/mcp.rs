/// The MCP server: a handle on the data dir that projects are read from.
#[derive(Debug, Clone)]
pub struct RhizzMcp {
    /// Data dir holding one directory per project (see [`crate::storage`]).
    data_dir: PathBuf,
    /// Tool dispatch table generated by `#[tool_router]`.
    tool_router: ToolRouter<Self>,
}

impl RhizzMcp {
    /// Creates a server that reads projects from `data_dir`.
    #[must_use]
    pub fn new(data_dir: PathBuf) -> Self {
        Self {
            data_dir,
            tool_router: Self::tool_router(),
        }
    }
}

/// Number of projects each `fetch_projects` page returns.
const PAGE_SIZE: usize = 10;

/// Default number of lines `read_file` returns when `limit` is omitted.
const READ_FILE_DEFAULT_LIMIT: usize = 100;

/// Largest window `read_file` returns in one call.
const READ_FILE_MAX_LIMIT: usize = 500;

/// Largest file `read_file` will load. Larger files are refused rather than
/// read whole into memory just to return a window of lines.
const READ_FILE_MAX_BYTES: u64 = 4 * 1024 * 1024;

