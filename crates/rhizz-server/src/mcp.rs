/// Maps one [`rhizz_core::mutation::ModelOp`] to the MCP tool that exposes
/// it, or `None` for the UI-only `create_component` convenience op.
///
/// Deliberately exhaustive with no wildcard arm: adding a `ModelOp` variant
/// breaks compilation here, forcing the same change to expose the tool (the
/// "new `ModelOp` gets a tool in the same change" rule from proposal 0003).
/// The `op_tool_mapping_covers_every_model_op` test then checks the mapped
/// names against the live `tools/list` response.
///
/// Only exercised by tests; the exhaustiveness is the point in normal builds.
#[allow(dead_code)]
const fn tool_name_for_op(op: &rhizz_core::mutation::ModelOp) -> Option<&'static str> {
    match op {
        rhizz_core::mutation::ModelOp::AddSystem { .. } => Some("add_system"),
        rhizz_core::mutation::ModelOp::AddDefinition { .. } => Some("add_component_definition"),
        rhizz_core::mutation::ModelOp::AddInstance { .. } => Some("add_instance"),
        rhizz_core::mutation::ModelOp::CreateComponent { .. } => None,
        rhizz_core::mutation::ModelOp::Reparent { .. } => Some("reparent_component"),
        rhizz_core::mutation::ModelOp::Rename { .. } => Some("rename_component"),
        rhizz_core::mutation::ModelOp::Update { .. } => Some("update_component"),
        rhizz_core::mutation::ModelOp::UpdateSystem { .. } => Some("update_system"),
        rhizz_core::mutation::ModelOp::Delete { .. } => Some("delete_component"),
        rhizz_core::mutation::ModelOp::DeleteSystem { .. } => Some("delete_system"),
        rhizz_core::mutation::ModelOp::AddConnection { .. } => Some("add_connection"),
        rhizz_core::mutation::ModelOp::ConnectComponents { .. } => Some("connect_components"),
        rhizz_core::mutation::ModelOp::DeleteConnectionByLabel { .. } => {
            Some("delete_connection_by_label")
        }
        rhizz_core::mutation::ModelOp::UpdateConnection { .. } => Some("update_connection"),
        rhizz_core::mutation::ModelOp::AddProtocol { .. } => Some("add_protocol"),
        rhizz_core::mutation::ModelOp::UpdateProtocol { .. } => Some("update_protocol"),
        rhizz_core::mutation::ModelOp::DeleteProtocol { .. } => Some("delete_protocol"),
    }
}

/// Encodes one diagnostic as the `check_project` JSON shape.
fn diagnostic_json(diagnostic: &rhizz_core::Diagnostic) -> Value {
    json!({
        "code": diagnostic.code.to_string(),
        "severity": diagnostic_severity(diagnostic.code.level),
        "file": diagnostic.file.as_ref().map(|f| f.display().to_string()),
        "line": diagnostic.line,
        "message": diagnostic.message,
    })
}

/// Encodes a successful mutation: whether it applied, the created path where
/// relevant, and any non-blocking warnings.
fn mutation_success(result: &rhizz_core::mutation::MutationResult) -> CallToolResult {
    let warnings: Vec<Value> = result.warnings.iter().map(diagnostic_json).collect();
    let payload = json!({
        "applied": true,
        "path": result.path,
        "warnings": warnings,
    });
    match serde_json::to_string(&payload) {
        Ok(text) => CallToolResult::success(vec![ContentBlock::text(text)]),
        Err(err) => {
            tracing::error!(?err, "mutation: failed to encode result");
            tool_error("failed to encode result")
        }
    }
}

/// Encodes a resolver refusal (`Err(diagnostics)`): the file was left
/// untouched. Reported as a tool error carrying the core diagnostic codes.
fn mutation_refused(diagnostics: &[rhizz_core::Diagnostic]) -> CallToolResult {
    let diagnostics: Vec<Value> = diagnostics.iter().map(diagnostic_json).collect();
    let payload = json!({ "applied": false, "diagnostics": diagnostics });
    serde_json::to_string(&payload).map_or_else(|_| tool_error("op refused"), tool_error)
}

/// Encodes a guard refusal (`applied: false`): unknown path, collision, or no
/// change. The file was left untouched. Reported as a tool error with the
/// core `E000` code, matching `MutationError::InvalidInput`.
fn mutation_not_applied() -> CallToolResult {
    let diagnostic = rhizz_core::Diagnostic::error(
        rhizz_core::DiagnosticCode::E000,
        "op refused (applied: false): unknown path, collision, or no change; file left untouched",
    );
    mutation_refused(std::slice::from_ref(&diagnostic))
}

/// A tool-level failure: reported to the client as `isError`, not as a
/// protocol error, so the model can see it and the session stays usable.
fn tool_error(message: impl Into<String>) -> CallToolResult {
    CallToolResult::error(vec![ContentBlock::text(message.into())])
}

/// The `updatedAt` stamp of a project, or an empty string when absent.
fn project_updated_at(project: &Value) -> &str {
    project
        .get("updatedAt")
        .and_then(Value::as_str)
        .unwrap_or("")
}

/// The `id` of a project, or an empty string when absent.
fn project_id(project: &Value) -> &str {
    project.get("id").and_then(Value::as_str).unwrap_or("")
}

/// The JSON `severity` string for a diagnostic `Level`.
const fn diagnostic_severity(level: rhizz_core::Level) -> &'static str {
    match level {
        rhizz_core::Level::Error => "error",
        rhizz_core::Level::Warning => "warning",
        rhizz_core::Level::Note => "note",
        rhizz_core::Level::Help => "help",
    }
}

/// The completion score in the same JSON shape as `rhizz --json build`.
fn score_json(report: &rhizz_core::ScoreReport) -> Value {
    let percent = (report.overall_percentage() * 10.0).round() / 10.0;
    json!({
        "components": {
            "complete": report.components.complete,
            "total": report.components.total(),
        },
        "connections": {
            "complete": report.connections.complete,
            "total": report.connections.total(),
        },
        "messages": {
            "complete": report.messages.complete,
            "total": report.messages.total(),
        },
        "overall": {
            "complete": report.overall_complete(),
            "percent": percent,
            "total": report.overall_total(),
        },
        "ports": {
            "complete": report.ports.complete,
            "total": report.ports.total(),
        },
        "system": report.project_name,
    })
}

/// Hand-written rather than `#[tool_handler]`: the macro generates `async`
/// trait methods without `.await`, which trips `clippy::unused_async`. The
/// methods return futures directly, matching the trait signatures.
impl ServerHandler for RhizzMcp {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new("rhizz", env!("CARGO_PKG_VERSION")))
    }

    fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> impl Future<Output = Result<CallToolResponse, ErrorData>> + MaybeSendFuture + '_ {
        let call = ToolCallContext::new(self, request, context);
        async move { self.tool_router.call(call).await }
    }

    fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> impl Future<Output = Result<ListToolsResult, ErrorData>> + MaybeSendFuture + '_ {
        std::future::ready(Ok(ListToolsResult::with_all_items(
            self.tool_router.list_all(),
        )))
    }

    fn get_tool(&self, name: &str) -> Option<Tool> {
        self.tool_router.get(name).cloned()
    }
}

