    /// Reads a window of lines of one project file.
    #[tool(
        name = "read_file",
        title = "Read project file",
        annotations(title = "Read project file", read_only_hint = true),
        description = "Read a window of lines of a file in a Rhizz project: pass the project id, a path relative to the project root, a 0-based `offset` (default 0) and a `limit` (default 100, maximum 500, larger values are refused). Returns the lines, `totalLines`, and a short content-hash `version` that changes whenever the file changes. Reading a directory or a missing path is a tool error."
    )]
    async fn read_file(
        &self,
        params: Parameters<ReadFileParams>,
    ) -> Result<CallToolResult, ErrorData> {
        let data_dir = self.data_dir.clone();
        let project = params.0.project;
        let path = params.0.path;
        let offset = params.0.offset.unwrap_or(0);
        let limit = match params.0.limit {
            Some(limit) if limit > READ_FILE_MAX_LIMIT => {
                return Ok(tool_error(format!(
                    "limit must be <= {READ_FILE_MAX_LIMIT}"
                )));
            }
            Some(limit) => limit,
            None => READ_FILE_DEFAULT_LIMIT,
        };

        let loaded = tokio::task::spawn_blocking(move || {
            let root = match storage::resolve_project(&data_dir, &project) {
                Ok(root) => root,
                Err(storage::ProjectError::Unknown(id)) => {
                    return Ok(tool_error(format!("unknown project `{id}`")));
                }
                Err(storage::ProjectError::Io(err)) => {
                    tracing::error!(?err, "read_file: failed to access project");
                    return Ok(tool_error("failed to read project"));
                }
            };
            let absolute = match storage::resolve_confined_path(&root, std::path::Path::new(&path))
            {
                Ok(absolute) => absolute,
                Err(err) => return Ok(tool_error(err.to_string())),
            };
            // Checked before opening: opening a FIFO or device would block this
            // worker thread, and a regular file is all the VFS ever stores.
            let Ok(metadata) = std::fs::symlink_metadata(&absolute) else {
                return Ok(tool_error("cannot read path"));
            };
            if !metadata.is_file() {
                return Ok(tool_error("path is not a regular file"));
            }
            if metadata.len() > READ_FILE_MAX_BYTES {
                return Ok(tool_error(format!(
                    "file is {} bytes, over the {READ_FILE_MAX_BYTES}-byte read limit",
                    metadata.len()
                )));
            }
            let Ok(content) = std::fs::read_to_string(&absolute) else {
                return Ok(tool_error("cannot read path"));
            };
            let lines: Vec<&str> = content.lines().skip(offset).take(limit).collect();
            let result = json!({
                "lines": lines,
                "totalLines": content.lines().count(),
                "version": storage::file_version(&content),
            });
            match serde_json::to_string(&result) {
                Ok(text) => Ok(CallToolResult::success(vec![ContentBlock::text(text)])),
                Err(err) => {
                    tracing::error!(?err, "read_file: failed to encode window");
                    Ok(tool_error("failed to encode window"))
                }
            }
        })
        .await;

        loaded.unwrap_or_else(|err| {
            tracing::error!(?err, "read_file: loader task failed");
            Ok(tool_error("failed to read file"))
        })
    }

