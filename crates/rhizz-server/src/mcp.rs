/// The MCP server: a handle on the data dir that projects are read from,
/// sharing the HTTP server's project locks (proposal 0004).
#[derive(Debug, Clone)]
pub struct RhizzMcp {
    /// Data dir holding one directory per project (see [`crate::storage`]).
    data_dir: PathBuf,
    /// Who holds which project — the same manager the HTTP routes use, so an
    /// edit through MCP and an edit through the web contend on one lock.
    locks: crate::locks::LockManager,
    /// Tool dispatch table generated by `#[tool_router]`.
    tool_router: ToolRouter<Self>,
}

impl RhizzMcp {
    /// Creates a server that reads projects from `data_dir` and contends on
    /// `locks`.
    #[must_use]
    pub fn new(data_dir: PathBuf, locks: crate::locks::LockManager) -> Self {
        Self {
            data_dir,
            locks,
            tool_router: Self::tool_router(),
        }
    }
}

