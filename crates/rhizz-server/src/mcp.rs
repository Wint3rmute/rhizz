//! Proof-of-concept Model Context Protocol (MCP) endpoint.
//!
//! Exposes a single tool, `fetch_projects`, over the MCP Streamable HTTP
//! transport. The endpoint is mounted at `/mcp` by [`crate::server::app`].
//!
//! This is a POC: there is no authentication, so it must not be exposed beyond
//! localhost.

use std::future::Future;
use std::path::PathBuf;

use rmcp::handler::server::router::tool::ToolRouter;
use rmcp::handler::server::tool::ToolCallContext;
use rmcp::model::{
    CallToolRequestParams, CallToolResponse, CallToolResult, ContentBlock, Implementation,
    ListToolsResult, PaginatedRequestParams, ServerCapabilities, ServerConfig, Tool,
};
use rmcp::service::{MaybeSendFuture, RequestContext, RoleServer};
use rmcp::{ErrorData, ServerHandler, tool, tool_router};

use crate::storage;

/// The MCP server: a handle on the data dir that projects are read from.
#[derive(Debug, Clone)]
pub struct RhizzMcp {
    /// Data dir holding one directory per project (see [`crate::storage`]).
    data_dir: PathBuf,
    /// Tool dispatch table generated by `#[tool_router]`.
    tool_router: ToolRouter<Self>,
}

impl RhizzMcp {
    /// Creates a server that reads projects from `data_dir`.
    #[must_use]
    pub fn new(data_dir: PathBuf) -> Self {
        Self {
            data_dir,
            tool_router: Self::tool_router(),
        }
    }
}

#[tool_router]
impl RhizzMcp {
    /// Lists the projects only (no nodes), as a JSON array in the text content.
    #[tool(
        name = "fetch_projects",
        description = "List all Rhizz projects available on this server (id, name, createdAt, updatedAt)."
    )]
    async fn fetch_projects(&self) -> Result<CallToolResult, ErrorData> {
        let data_dir = self.data_dir.clone();
        let loaded = tokio::task::spawn_blocking(move || storage::load_vfs(&data_dir)).await;
        let vfs = match loaded {
            Ok(Ok(vfs)) => vfs,
            Ok(Err(err)) => {
                tracing::error!(?err, "fetch_projects: failed to load VFS");
                return Ok(tool_error("failed to load projects"));
            }
            Err(err) => {
                tracing::error!(?err, "fetch_projects: loader task failed");
                return Ok(tool_error("failed to load projects"));
            }
        };
        let projects = vfs
            .get("projects")
            .cloned()
            .unwrap_or_else(|| serde_json::json!([]));
        match serde_json::to_string(&projects) {
            Ok(text) => Ok(CallToolResult::success(vec![ContentBlock::text(text)])),
            Err(err) => {
                tracing::error!(?err, "fetch_projects: failed to encode projects");
                Ok(tool_error("failed to encode projects"))
            }
        }
    }
}

/// A tool-level failure: reported to the client as `isError`, not as a
/// protocol error, so the model can see it and the session stays usable.
fn tool_error(message: &'static str) -> CallToolResult {
    CallToolResult::error(vec![ContentBlock::text(message)])
}

/// Hand-written rather than `#[tool_handler]`: the macro generates `async`
/// trait methods without `.await`, which trips `clippy::unused_async`. The
/// methods return futures directly, matching the trait signatures.
impl ServerHandler for RhizzMcp {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new("rhizz", env!("CARGO_PKG_VERSION")))
    }

    fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> impl Future<Output = Result<CallToolResponse, ErrorData>> + MaybeSendFuture + '_ {
        let call = ToolCallContext::new(self, request, context);
        async move { self.tool_router.call(call).await }
    }

    fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> impl Future<Output = Result<ListToolsResult, ErrorData>> + MaybeSendFuture + '_ {
        std::future::ready(Ok(ListToolsResult::with_all_items(
            self.tool_router.list_all(),
        )))
    }

    fn get_tool(&self, name: &str) -> Option<Tool> {
        self.tool_router.get(name).cloned()
    }
}

#[cfg(test)]
mod tests {
    use axum::Router;
    use axum::body::Body;
    use axum::http::{Request, StatusCode, header};
    use serde_json::{Value, json};
    use tower::ServiceExt as _;

    use crate::server::app;

    const MCP_SESSION_ID: &str = "mcp-session-id";

    /// Sends one JSON-RPC message to `/mcp` and returns the status, the
    /// session id header (if any) and the parsed JSON-RPC payload (if any).
    async fn post_rpc(
        app: &Router,
        message: &Value,
        session: Option<&str>,
    ) -> (StatusCode, Option<String>, Option<Value>) {
        let mut builder = Request::builder()
            .method("POST")
            .uri("/mcp")
            .header(header::HOST, "localhost")
            .header(header::CONTENT_TYPE, "application/json")
            .header(header::ACCEPT, "application/json, text/event-stream");
        if let Some(session) = session {
            builder = builder.header(MCP_SESSION_ID, session);
        }
        let request = builder.body(Body::from(message.to_string())).unwrap();
        let response = app.clone().oneshot(request).await.unwrap();

        let status = response.status();
        let session_id = response
            .headers()
            .get(MCP_SESSION_ID)
            .map(|value| value.to_str().unwrap().to_owned());
        let bytes = axum::body::to_bytes(response.into_body(), 1024 * 1024)
            .await
            .unwrap();
        let text = String::from_utf8(bytes.to_vec()).unwrap();
        let payload = parse_payload(&text);
        (status, session_id, payload)
    }

    /// The reply is either a bare JSON object or a server-sent-events stream
    /// whose `data:` lines carry the JSON-RPC message.
    fn parse_payload(text: &str) -> Option<Value> {
        let trimmed = text.trim();
        if trimmed.is_empty() {
            return None;
        }
        if trimmed.starts_with('{') {
            return serde_json::from_str(trimmed).ok();
        }
        trimmed
            .lines()
            .filter_map(|line| line.strip_prefix("data:"))
            .map(str::trim)
            .find(|data| !data.is_empty())
            .map(|data| serde_json::from_str(data).unwrap())
    }

    fn initialize_request() -> Value {
        json!({
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {
                "protocolVersion": "2025-06-18",
                "capabilities": {},
                "clientInfo": { "name": "rhizz-test", "version": "0.0.0" }
            }
        })
    }

    /// Runs the `initialize` handshake and returns the session id to reuse.
    /// The session lives in the router's session manager, so every request of
    /// a test must go through the same router (as the real server does).
    async fn handshake(app: &Router) -> String {
        let (status, session, _) = post_rpc(app, &initialize_request(), None).await;
        assert_eq!(status, StatusCode::OK);
        let session = session.expect("initialize must return a session id");

        let initialized = json!({ "jsonrpc": "2.0", "method": "notifications/initialized" });
        let (status, _, _) = post_rpc(app, &initialized, Some(&session)).await;
        assert_eq!(status, StatusCode::ACCEPTED);
        session
    }

    fn write_drone_project(data_dir: &std::path::Path) {
        let drone = data_dir.join("drone");
        std::fs::create_dir_all(&drone).unwrap();
        std::fs::write(drone.join("system.hcl"), "system \"drone\" {}\n").unwrap();
    }

    #[tokio::test]
    async fn tools_list_exposes_exactly_one_tool_named_fetch_projects() {
        let tmp = tempfile::tempdir().unwrap();
        let app = app(tmp.path().to_path_buf());
        let session = handshake(&app).await;

        let list = json!({ "jsonrpc": "2.0", "id": 2, "method": "tools/list" });
        let (status, _, payload) = post_rpc(&app, &list, Some(&session)).await;
        assert_eq!(status, StatusCode::OK);

        let payload = payload.expect("tools/list must reply");
        let tools = payload["result"]["tools"].as_array().unwrap();
        assert_eq!(tools.len(), 1, "expected exactly one tool: {tools:?}");
        assert_eq!(tools[0]["name"], json!("fetch_projects"));
    }

    #[tokio::test]
    async fn tools_call_fetch_projects_lists_the_project_ids() {
        let tmp = tempfile::tempdir().unwrap();
        write_drone_project(tmp.path());
        let app = app(tmp.path().to_path_buf());
        let session = handshake(&app).await;

        let call = json!({
            "jsonrpc": "2.0",
            "id": 3,
            "method": "tools/call",
            "params": { "name": "fetch_projects", "arguments": {} }
        });
        let (status, _, payload) = post_rpc(&app, &call, Some(&session)).await;
        assert_eq!(status, StatusCode::OK);

        let payload = payload.expect("tools/call must reply");
        assert_ne!(payload["result"]["isError"], json!(true), "{payload}");
        let text = payload["result"]["content"][0]["text"].as_str().unwrap();
        let projects: Value = serde_json::from_str(text).unwrap();
        let projects = projects.as_array().unwrap();
        assert_eq!(projects.len(), 1);
        assert_eq!(projects[0]["id"], json!("drone"));
        assert_eq!(projects[0]["name"], json!("drone"));
        assert!(projects[0].get("nodes").is_none());
    }

    #[tokio::test]
    async fn tools_call_fetch_projects_on_empty_data_dir_returns_empty_list() {
        let tmp = tempfile::tempdir().unwrap();
        let app = app(tmp.path().to_path_buf());
        let session = handshake(&app).await;

        let call = json!({
            "jsonrpc": "2.0",
            "id": 4,
            "method": "tools/call",
            "params": { "name": "fetch_projects", "arguments": {} }
        });
        let (status, _, payload) = post_rpc(&app, &call, Some(&session)).await;
        assert_eq!(status, StatusCode::OK);

        let payload = payload.expect("tools/call must reply");
        assert_ne!(payload["result"]["isError"], json!(true), "{payload}");
        let text = payload["result"]["content"][0]["text"].as_str().unwrap();
        let projects: Value = serde_json::from_str(text).unwrap();
        assert_eq!(projects, json!([]));
    }
}
