/// Encodes one diagnostic as the `check_project` JSON shape.
fn diagnostic_json(diagnostic: &rhizz_core::Diagnostic) -> Value {
    json!({
        "code": diagnostic.code.to_string(),
        "severity": diagnostic_severity(diagnostic.code.level),
        "file": diagnostic.file.as_ref().map(|f| f.display().to_string()),
        "line": diagnostic.line,
        "message": diagnostic.message,
    })
}

/// Encodes a successful mutation: whether it applied, the created path where
/// relevant, and any non-blocking warnings.
fn mutation_success(result: &rhizz_core::mutation::MutationResult) -> CallToolResult {
    let warnings: Vec<Value> = result.warnings.iter().map(diagnostic_json).collect();
    let payload = json!({
        "applied": true,
        "path": result.path,
        "warnings": warnings,
    });
    match serde_json::to_string(&payload) {
        Ok(text) => CallToolResult::success(vec![ContentBlock::text(text)]),
        Err(err) => {
            tracing::error!(?err, "mutation: failed to encode result");
            tool_error("failed to encode result")
        }
    }
}

/// Encodes a resolver refusal (`Err(diagnostics)`): the file was left
/// untouched. Reported as a tool error carrying the core diagnostic codes.
fn mutation_refused(diagnostics: &[rhizz_core::Diagnostic]) -> CallToolResult {
    let diagnostics: Vec<Value> = diagnostics.iter().map(diagnostic_json).collect();
    let payload = json!({ "applied": false, "diagnostics": diagnostics });
    serde_json::to_string(&payload).map_or_else(|_| tool_error("op refused"), tool_error)
}

/// Encodes a guard refusal (`applied: false`): unknown path, collision, or no
/// change. The file was left untouched. Reported as a tool error with the
/// core `E000` code, matching `MutationError::InvalidInput`.
fn mutation_not_applied() -> CallToolResult {
    let diagnostic = rhizz_core::Diagnostic::error(
        rhizz_core::DiagnosticCode::E000,
        "op refused (applied: false): unknown path, collision, or no change; file left untouched",
    );
    mutation_refused(std::slice::from_ref(&diagnostic))
}

/// A tool-level failure: reported to the client as `isError`, not as a
/// protocol error, so the model can see it and the session stays usable.
fn tool_error(message: impl Into<String>) -> CallToolResult {
    CallToolResult::error(vec![ContentBlock::text(message.into())])
}

/// Emit exactly one info-level audit event per MCP tool call, on success
/// *and* on refusal/error paths, so an operator watching with `RUST_LOG=info`
/// sees who did what. One line per call, greppable as e.g.
/// `mcp tool=create_file project=drone target=views/main.hcl outcome=ok …`.
///
/// Structured fields: `tool` (tool name), `project` (the `project` argument,
/// "" when the tool takes none), `target` (the acted-on `path` / `scopePath`
/// / `label` argument, "" when none), `outcome` (`ok` | `refused` | `error`),
/// `elapsed_ms`, `codes` (comma-joined diagnostic codes from a refused
/// payload, "" otherwise), `version` / `total_lines` (file-write size
/// signals from a successful file payload, "" / 0 when absent — never file
/// contents).
fn log_tool_call(
    tool: &str,
    arguments: Option<&serde_json::Map<String, serde_json::Value>>,
    result: &Result<CallToolResponse, ErrorData>,
    elapsed: std::time::Duration,
) {
    let project = arguments
        .and_then(|args| args.get("project"))
        .and_then(serde_json::Value::as_str)
        .unwrap_or("");
    let mut target = "";
    for key in ["path", "scopePath", "label"] {
        if let Some(value) = arguments
            .and_then(|args| args.get(key))
            .and_then(serde_json::Value::as_str)
            && !value.is_empty()
        {
            target = value;
            break;
        }
    }

    // Refusals are tool errors (`isError`); protocol failures are `Err`.
    // Anything else that completed (including `InputRequired`/`Task`, which
    // no Rhizz tool produces) did not succeed, so it audits as an error.
    let payload: Option<serde_json::Value> = match result {
        Ok(CallToolResponse::Complete(completed)) => completed
            .content
            .iter()
            .find_map(|block| match block {
                ContentBlock::Text(text) => Some(text.text.as_str()),
                _ => None,
            })
            .and_then(|text| serde_json::from_str(text).ok()),
        _ => None,
    };
    let outcome = match result {
        Ok(CallToolResponse::Complete(completed))
            if completed.is_error.is_some_and(|is_err| is_err) =>
        {
            "refused"
        }
        Ok(CallToolResponse::Complete(_)) => "ok",
        // Protocol failures are `Err`; `InputRequired`/`Task` (which no
        // Rhizz tool produces) did not succeed either.
        _ => "error",
    };
    let codes = payload
        .as_ref()
        .and_then(|json| json.get("diagnostics"))
        .and_then(serde_json::Value::as_array)
        .map(|diagnostics| {
            diagnostics
                .iter()
                .filter_map(|diagnostic| diagnostic.get("code"))
                .filter_map(serde_json::Value::as_str)
                .collect::<Vec<_>>()
                .join(",")
        })
        .unwrap_or_default();
    let version = payload
        .as_ref()
        .and_then(|json| json.get("version"))
        .and_then(serde_json::Value::as_str)
        .unwrap_or("");
    let total_lines = payload
        .as_ref()
        .and_then(|json| json.get("totalLines"))
        .and_then(serde_json::Value::as_u64)
        .unwrap_or(0);

    tracing::info!(
        tool = %tool,
        project = %project,
        target = %target,
        outcome = %outcome,
        elapsed_ms = u64::try_from(elapsed.as_millis()).unwrap_or(u64::MAX),
        codes = %codes,
        version = %version,
        total_lines = total_lines,
        "mcp tool call",
    );
}

/// The lock/version tail appended to read-tool payloads so an AI loop sees
/// staleness without another call: the short content-hash `version` plus who holds
/// the lock (`lockedBy`, and `lockExpiresAt` when held).
fn lock_state(
    locks: &crate::locks::LockManager,
    project_id: &str,
    version: String,
) -> serde_json::Map<String, Value> {
    let mut state = serde_json::Map::new();
    state.insert("version".to_owned(), Value::String(version));
    state.insert("lockedBy".to_owned(), Value::Null);
    if let Some(info) = locks.get(project_id) {
        state.insert("lockedBy".to_owned(), Value::String(info.holder));
        state.insert(
            "lockExpiresAt".to_owned(),
            Value::String(storage::format_rfc3339_millis(storage::millis_since_epoch(
                info.expires_at,
            ))),
        );
    }
    state
}

/// The `updatedAt` stamp of a project, or an empty string when absent.
